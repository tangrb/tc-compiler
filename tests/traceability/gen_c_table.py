#!/usr/bin/env python3
"""Generate the C diagnostic-code table from tests/traceability/codes.json.

Outputs:
    src/diagnostic/codes.inc   X-macro entries (enum + table)
    src/diagnostic/table.c     TcDiagInfo table

`--check` verifies both committed files are up to date.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
CODES = Path(__file__).resolve().parent / "codes.json"
INC = ROOT / "src" / "diagnostic" / "codes.inc"
TABLE = ROOT / "src" / "diagnostic" / "table.c"

STAGE = {
    "LEX": "TC_STAGE_MASK_LEX",
    "SYN": "TC_STAGE_MASK_SYN",
    "LEX/SYN": "TC_STAGE_MASK_LEX_SYN",
    "IMPORT": "TC_STAGE_MASK_IMPORT",
    "SEM": "TC_STAGE_MASK_SEM",
    "CT": "TC_STAGE_MASK_CT",
    "RT": "TC_STAGE_MASK_RT",
}

GROUP = {
    "lex_syn": "TC_DIAG_GROUP_LEX_SYN",
    "name_module": "TC_DIAG_GROUP_NAME_MODULE",
    "type_decl_control": "TC_DIAG_GROUP_TYPE_DECL_CONTROL",
    "safety_const": "TC_DIAG_GROUP_SAFETY_CONST",
    "runtime": "TC_DIAG_GROUP_RUNTIME",
}


def cstr(s: str) -> str:
    out = ['"']
    for ch in s:
        o = ord(ch)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif o < 0x20 or o == 0x7F:
            out.append(f"\\x{o:02x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def load() -> list[dict]:
    payload = json.loads(CODES.read_text(encoding="utf-8"))
    codes = payload["codes"]
    if len(codes) != 80:
        raise SystemExit(f"codes.json has {len(codes)} codes, expected 80")
    return codes


def build_inc(codes: list[dict]) -> str:
    lines = [
        "/* GENERATED by tests/traceability/gen_c_table.py from codes.json.",
        " * Do not edit by hand.  Normative source: standard §12.3/§12.5.1. */",
    ]
    for c in codes:
        stage = STAGE[c["stage"]]
        report = STAGE[c["report_stage"]]
        group = GROUP[c["group"]]
        w = 0
        if c["w_sensitive"]:
            w = 1
        lines.append(
            "TC_DIAG_ENTRY({code}, {stage}, {report}, {group}, {w}, {rank}, {clause}, {print_name}, {trigger},\n"
            "              {position})".format(
                code=c["code"],
                stage=stage,
                report=report,
                group=group,
                w=w,
                rank=c["same_site_rank"],
                clause=c["clause_rank"],
                print_name=cstr(c["print_name"]),
                trigger=cstr(c["trigger"]),
                position=cstr(c["position"]),
            )
        )
    return "\n".join(lines) + "\n"


def build_table(codes: list[dict]) -> str:
    first_re = next(c["code"] for c in codes if c["kind"] == "re")
    last = codes[-1]["code"]
    return f"""/* GENERATED by tests/traceability/gen_c_table.py from codes.json.
 * Do not edit by hand.  Normative source: standard §12.3/§12.5.1. */
#include "diagnostic/diagnostic.h"

#include "base/assert.h"

const TcDiagInfo tc_diag_table[TC_DIAG_CODE_COUNT] = {{
#define TC_DIAG_ENTRY(name, stage, report_stage, group, w, rank, clause, print_name, trigger, \\
                            position)                                                                  \\
    [name] = {{#name, print_name, stage, report_stage, group, (uint8_t)(w), (uint8_t)(rank),           \\
             (uint8_t)(clause), trigger, position}},
#include "diagnostic/codes.inc"
#undef TC_DIAG_ENTRY
}};

TC_STATIC_ASSERT(sizeof(tc_diag_table) / sizeof(tc_diag_table[0]) == TC_DIAG_CODE_COUNT, __LINE__);
TC_STATIC_ASSERT((unsigned){first_re} == TC_DIAG_CE_COUNT, __LINE__);
TC_STATIC_ASSERT((unsigned){last} + 1u == TC_DIAG_CODE_COUNT, __LINE__);
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    codes = load()
    inc = build_inc(codes)
    table = build_table(codes)
    if args.check:
        stale = False
        for path, text in ((INC, inc), (TABLE, table)):
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"FAIL: stale generated file {path}", file=sys.stderr)
                stale = True
        if stale:
            return 1
        print("OK: C diagnostic table matches codes.json")
        return 0
    INC.write_text(inc, encoding="utf-8")
    TABLE.write_text(table, encoding="utf-8")
    print(f"wrote {INC} and {TABLE} ({len(codes)} codes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
