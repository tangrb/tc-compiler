#!/bin/sh
# 生成 1000 变量定义 + 1000 赋值的 stress 基线文件
set -e

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="$ROOT/tests/stress/bench_baseline.tc"

{
    echo "; Auto-generated by scripts/vm/gen_bench_baseline.sh"
    echo "; 1000 var definitions + 1000 assignments (int32 strict add)"
    i=0
    while [ "$i" -lt 1000 ]; do
        echo "var v$i: int32 = $i"
        i=$((i + 1))
    done
    i=0
    while [ "$i" -lt 1000 ]; do
        echo "v$i = add(int32, v$i, 1)"
        i=$((i + 1))
    done
    echo "writeln(int32, v999)"
} > "$OUT"

echo "wrote $OUT"
